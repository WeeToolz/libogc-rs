//! Development mode selection and the generated, identity-checked run launcher.
use std::path::Path;

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Mode {
    pub development: bool,
    explicit: bool,
}
impl Mode {
    pub fn take_flag(&mut self, flag: &str) -> Result<bool, String> {
        let value = match flag {
            "--dev" => true,
            "--no-dev" => false,
            _ => return Ok(false),
        };
        if self.explicit && self.development != value {
            return Err("--dev and --no-dev cannot be combined".into());
        }
        self.development = value;
        self.explicit = true;
        Ok(true)
    }
}
fn quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}
pub fn launcher(
    dol: &Path,
    manifest: &Path,
    runner: &Path,
    features: &str,
    revision: &str,
    changes: &str,
) -> String {
    format!(
        r#"#!/bin/zsh
# Generated by cargo xtask build-dol --dev.
set -e
export WII_BUILD_FEATURES={features}
export WII_SOURCE_REVISION={revision}
export WII_SOURCE_CHANGES={changes}
export WII_PROBE_RECOVERY_RESET_MS="${{WII_PROBE_RECOVERY_RESET_MS:-180000}}"
export WII_PROBE_TIMEOUT="${{WII_PROBE_TIMEOUT:-240}}"
python3 - {manifest} {dol} <<'PY'
import hashlib,json,pathlib,sys
manifest=json.loads(pathlib.Path(sys.argv[1]).read_text())
dol=pathlib.Path(sys.argv[2])
if manifest.get('development') is not True:
    raise SystemExit('This DOL has no development wrapper. Rebuild with --dev.')
if hashlib.sha256(dol.read_bytes()).hexdigest()!=manifest['dol_sha256']:
    raise SystemExit('DOL identity changed. Rebuild its development launcher.')
PY
exec {runner} {dol} "$@"
"#,
        features = quote(features),
        revision = quote(revision),
        changes = quote(changes),
        manifest = quote(&manifest.to_string_lossy()),
        dol = quote(&dol.to_string_lossy()),
        runner = quote(&runner.to_string_lossy())
    )
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn normal_is_default_and_modes_are_explicit_boolean_flags() {
        let mut mode = Mode::default();
        assert!(!mode.development);
        assert!(mode.take_flag("--dev").unwrap());
        assert!(mode.development);
        assert!(!mode.take_flag("--output").unwrap());
        assert!(mode.take_flag("--no-dev").is_err());
        let mut normal = Mode::default();
        assert!(normal.take_flag("--no-dev").unwrap());
        assert!(!normal.development);
    }
    #[test]
    fn generated_launcher_checks_actual_dol_identity_and_quotes_shell_data() {
        let text = launcher(
            Path::new("/a/dol's file.dol"),
            Path::new("/a/manifest.json"),
            Path::new("/a/run.command"),
            "dev-wrapper",
            "abc",
            "dirty: $HOME `id` 'x'",
        );
        assert!(text.contains("manifest.get('development') is not True"));
        assert!(text.contains("hashlib.sha256(dol.read_bytes()).hexdigest()"));
        assert!(text.contains("'/a/dol'\\''s file.dol'"));
        assert!(text.contains("'dirty: $HOME `id` '\\''x'\\'''"));
        assert!(text.contains("exec '/a/run.command'"));
    }
}
